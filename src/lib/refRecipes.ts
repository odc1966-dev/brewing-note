type Spec = [at: string | null, amount: number | null, styles?: string, memo?: string, label?: string];

const sec = (t: string) => {
  const [m, s] = t.split(":").map(Number);
  return m * 60 + s;
};

/** 단계 목록. bloom=true 면 첫 단계가 뜸 들이기, 나머지는 N차 푸어 */
function S(spec: Spec[], bloom = true): RecipeStep[] {
  let n = 0;
  return spec.map((x, i) => {
    const isBloom = bloom && i === 0;
    if (!isBloom && !x[4]) n++;
    return {
      id: `s${i}`,
      label: x[4] ?? (isBloom ? "뜸 들이기" : `${n}차 푸어`),
      at: x[0] == null ? null : sec(x[0]),
      amount: x[1],
      styles: x[2] ? x[2].split(",") : [],
      duration: null,
      memo: x[3] ?? "",
    };
  });
}

